function pick(list: string[], avoid?: string): string {
  if (list.length === 0) return avoid?.trim() || "чепуха";
  if (list.length === 1) return list[0]!;
  const trimmed = avoid?.trim();
  for (let i = 0; i < 8; i++) {
    const word = list[Math.floor(Math.random() * list.length)]!;
    if (!trimmed || word !== trimmed) return word;
  }
  return list[Math.floor(Math.random() * list.length)]!;
}

/** Подбирает список по тексту подсказки. */
export function wordsForHint(prompt: string): string[] {
  const p = prompt.toLowerCase();

  if (p.includes("междометие") || p.includes("возглас")) return INTERJ;
  if (p.includes("звук") || p.includes("шум")) return SOUNDS;
  if (p.includes("имя собственн") || p.includes("имя ")) return NAMES;
  if (p.includes("професси") || p.includes("род занятий")) return JOBS;
  if (p.includes("часть тела")) return BODY;
  if (p.includes("чувство") || p.includes("эмоци")) return FEELINGS;
  if (p.includes("число") || p.includes("количество")) return NUMBERS;
  if (p.includes("фраз") || p.includes("любое слово")) return PHRASES;
  if (p.includes("наречие")) return ADV;

  if (p.includes("повелительн")) return VERB_IMP;
  if (p.includes("инфинитив")) return VERB_INF;
  if (p.includes("глагол") && p.includes("множественн")) return VERB_PAST_PL;
  if (p.includes("прошедш") || (p.includes("глагол") && !p.includes("инфинитив"))) {
    return VERB_PAST;
  }

  if (p.includes("прилагательн") && p.includes("творительн") && p.includes("женск")) {
    return ADJ_INS_F;
  }
  if (p.includes("краткое прилагательн") || p.includes("оценка")) return ADJ_SHORT;
  if (p.includes("прилагательн")) return ADJ;

  if (p.includes("после «у»") || p.includes('после "у"') || p.includes("после у")) {
    return PLACE_U;
  }
  if (p.includes("после «к»") || p.includes('после "к"') || p.includes("после к")) {
    return PLACE_K;
  }
  if (p.includes("после «в") || p.includes("куда?") || p.includes("помещение, куда")) {
    return PLACE_V;
  }
  if (p.includes("предложн") && (p.includes("мест") || p.includes("без предлога"))) {
    return PREP_PLACE;
  }

  if (p.includes("родительн") && p.includes("множественн")) return GEN_PL;
  if (p.includes("творительн")) return INS;
  if (p.includes("дательн")) return DAT;
  if (p.includes("винительн")) return ACC;
  if (p.includes("родительн")) return GEN;
  if (p.includes("существительн") || p.includes("мифическ") || p.includes("кто? что?")) {
    return NOM;
  }

  return FALLBACK;
}

export function randomWordForHint(prompt: string, current?: string): string {
  return pick(wordsForHint(prompt), current);
}
